-- Banco `sdcac` — padroes, notas, alertas e metricas
--
--     psql -d sdcac -v ON_ERROR_STOP=1 -f database/sdcac/001_schema.sql
--
-- E a saida do software: o que o motor calculou e o que o avaliador mediu.
-- O que a v2 acrescenta — usuarios, configuracoes editaveis, fila de job e
-- auditoria de consulta — esta em docs/software.md, secao 7, e NAO entra aqui
-- antes de existir codigo que use.

CREATE TYPE configuration AS ENUM ('C0', 'C1', 'C2', 'C3');

-- As quatro faixas de exibicao. A avaliacao usa o score bruto, sem teto: faixa
-- empatada em 100 viraria degrau na curva precisao-revocacao da D-14.
CREATE TYPE risk_band AS ENUM ('normal', 'low', 'medium', 'high');

-- As duas unidades da D-12, declaradas separadamente, mais o usuario-dia que
-- e o denominador do falso positivo.
CREATE TYPE metric_unit AS ENUM ('event', 'episode', 'user_day');

-- ---------------------------------------------------------------------------
-- O padrao de cada funcionario (D-24 e D-29)
--
-- Uma versao por janela de treino. As caracteristicas vao em jsonb porque sao
-- sete grandezas de formatos diferentes — mediana e MAD de contagem, histograma
-- de 24 posicoes, conjunto de recursos — e nenhuma regra consulta uma delas
-- isoladamente pelo banco: quem le e o nucleo, inteiro, de uma vez.
-- ---------------------------------------------------------------------------

CREATE TABLE baselines (
    run_id       integer  NOT NULL,
    employee_id  integer  NOT NULL,
    version      smallint NOT NULL,
    window_start date     NOT NULL,
    window_end   date     NOT NULL,
    peer_group   boolean  NOT NULL DEFAULT false,
    features     jsonb    NOT NULL,
    PRIMARY KEY (run_id, employee_id, version),
    CONSTRAINT baselines_janela_coerente CHECK (window_end > window_start),
    CONSTRAINT baselines_features_e_objeto CHECK (jsonb_typeof(features) = 'object')
);

COMMENT ON COLUMN baselines.peer_group IS 'Verdadeiro quando o funcionario nao tinha historico suficiente e caiu no padrao do grupo de pares, pela D-29. Precisa aparecer no resultado: e limitacao declarada, nao detalhe.';

-- ---------------------------------------------------------------------------
-- Execucoes de pontuacao (D-34)
--
-- Uma linha por (semente x configuracao). O `config_hash` e NOT NULL de
-- proposito: a secao 3.7 da Metodologia promete ao leitor que cada execucao
-- grava semente, configuracao e pesos. Execucao sem hash e erro, nao aviso.
-- ---------------------------------------------------------------------------

CREATE TABLE scoring_runs (
    scoring_run_id  integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          integer       NOT NULL,
    config          configuration NOT NULL,
    config_name     text          NOT NULL,
    config_hash     text          NOT NULL,
    weights_version text          NOT NULL,
    code_sha        text          NOT NULL,
    exploratory     boolean       NOT NULL DEFAULT false,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    UNIQUE (run_id, config, config_hash, exploratory)
);

COMMENT ON COLUMN scoring_runs.exploratory IS 'Verdadeiro quando a configuracao nao e um dos presets canonicos da D-33. Resultado exploratorio nao vai ao artigo, e a coluna existe para que isso seja verificavel depois, nao lembrado.';

-- ---------------------------------------------------------------------------
-- As notas, decompostas (D-36)
--
-- Cinco parcelas, sempre. Numero unico impediria a decomponibilidade que a
-- secao 3.9 da Metodologia promete, e a regra de usabilidade exige.
-- ---------------------------------------------------------------------------

CREATE TABLE risk_scores (
    scoring_run_id integer   NOT NULL REFERENCES scoring_runs,
    event_id       uuid      NOT NULL,
    c0             numeric(6, 2) NOT NULL,
    d1             numeric(6, 2),
    d2             numeric(6, 2),
    d3_conduct     numeric(6, 2),
    d3_posture     numeric(6, 2),
    final_raw      numeric(8, 2) NOT NULL,
    band           risk_band NOT NULL,
    PRIMARY KEY (scoring_run_id, event_id)
);

COMMENT ON TABLE risk_scores IS 'As colunas de dimensao sao nulas quando a configuracao nao liga aquela dimensao: na C0 so c0 tem valor. Nulo aqui significa "nao avaliada", e e diferente de zero, que significa "avaliada e sem risco".';

-- ---------------------------------------------------------------------------
-- Alertas
--
-- Alerta por evento OU por funcionario numa janela: a D3 alarma sobre alguem
-- num periodo, nao sobre um evento. A restricao abaixo e a D-12 aparecendo no
-- schema.
-- ---------------------------------------------------------------------------

CREATE TABLE alerts (
    alert_id       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scoring_run_id integer     NOT NULL REFERENCES scoring_runs,
    event_id       uuid,
    employee_id    integer,
    window_start   timestamptz,
    window_end     timestamptz,
    band           risk_band   NOT NULL,
    threshold      numeric(8, 2) NOT NULL,
    raised_at      timestamptz NOT NULL,
    CONSTRAINT alerts_alvo_definido CHECK (
        (event_id IS NOT NULL AND employee_id IS NULL)
        OR (event_id IS NULL AND employee_id IS NOT NULL
            AND window_start IS NOT NULL AND window_end IS NOT NULL)
    )
);

COMMENT ON COLUMN alerts.raised_at IS 'Instante do evento que disparou o alerta, em tempo simulado. O atraso de deteccao se mede contra o inicio do episodio, nunca contra o relogio de quem rodou o script.';

-- ---------------------------------------------------------------------------
-- Metricas
--
-- Gravadas pelo avaliador, que e o unico que le o gabarito. A aplicacao exibe
-- o que esta aqui; ela nao calcula metrica.
-- ---------------------------------------------------------------------------

CREATE TABLE metrics (
    scoring_run_id       integer     NOT NULL REFERENCES scoring_runs,
    unit                 metric_unit NOT NULL,
    threshold            numeric(8, 2) NOT NULL,
    recall               numeric(6, 4),
    false_positive_rate  numeric(6, 4),
    detection_delay_days numeric(6, 2),
    positives            integer,
    negatives            integer,
    PRIMARY KEY (scoring_run_id, unit, threshold)
);

COMMENT ON TABLE metrics IS 'Uma linha por limiar, e nao um ponto unico: a D-14 preve comparar curvas precisao-revocacao se a C0 nao alcancar revocacao 0,90 em limiar nenhum.';
